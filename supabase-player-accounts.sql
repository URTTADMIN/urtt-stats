create table if not exists public.player_accounts (
  id bigint generated by default as identity primary key,
  pseudo text not null unique,
  discord_name text not null,
  access_code text not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

alter table public.player_accounts enable row level security;

drop policy if exists "Public can create player accounts" on public.player_accounts;
create policy "Public can create player accounts"
on public.player_accounts
for insert
to anon, authenticated
with check (true);

drop policy if exists "Public can login player accounts" on public.player_accounts;
create policy "Public can login player accounts"
on public.player_accounts
for select
to anon, authenticated
using (true);

alter table public.race_predictions
add column if not exists user_id uuid references auth.users(id) on delete set null;

alter table public.race_predictions
add column if not exists player_id bigint references public.player_accounts(id) on delete set null;

create index if not exists race_predictions_player_id_idx
on public.race_predictions(player_id);

do $$
begin
  if not exists (
    select 1
    from public.race_predictions
    where player_id is not null
    group by player_id, race_id
    having count(*) > 1
  ) then
    create unique index if not exists race_predictions_one_player_per_race_idx
    on public.race_predictions(player_id, race_id)
    where player_id is not null;
  end if;
end $$;

drop policy if exists "Public can create race predictions" on public.race_predictions;
create policy "Public can create race predictions"
on public.race_predictions
for insert
to anon, authenticated
with check (true);

drop policy if exists "Authenticated users can delete race predictions" on public.race_predictions;
create policy "Authenticated users can delete race predictions"
on public.race_predictions
