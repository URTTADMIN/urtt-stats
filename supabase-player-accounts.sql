to authenticated
using (true);

create table if not exists public.guess_driver_results (
  id bigint generated by default as identity primary key,
  player_id bigint references public.player_accounts(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  pseudo text not null,
  discord_name text,
  category_id text not null,
  challenge_day date not null,
  driver_id bigint not null,
  attempts integer not null default 0,
  score integer not null default 1,
  won boolean not null default true,
  created_at timestamptz not null default now(),
  unique(player_id, category_id, challenge_day)
);

alter table public.guess_driver_results
add column if not exists player_id bigint references public.player_accounts(id) on delete cascade;

alter table public.guess_driver_results
add column if not exists user_id uuid references auth.users(id) on delete cascade;

alter table public.guess_driver_results
add column if not exists score integer not null default 1;

alter table public.guess_driver_results
alter column user_id drop not null;

update public.guess_driver_results
set score = greatest(1, 11 - greatest(1, coalesce(attempts, 1)))
where won is true and (score is null or score <= 1);

do $$
begin
  alter table public.guess_driver_results
  drop constraint if exists guess_driver_results_user_id_category_id_challenge_day_key;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'guess_driver_results_player_id_category_id_challenge_day_key'
  ) then
    alter table public.guess_driver_results
    add constraint guess_driver_results_player_id_category_id_challenge_day_key
    unique (player_id, category_id, challenge_day);
  end if;
end $$;

create index if not exists guess_driver_results_player_category_day_idx
on public.guess_driver_results(player_id, category_id, challenge_day desc);

alter table public.guess_driver_results enable row level security;

